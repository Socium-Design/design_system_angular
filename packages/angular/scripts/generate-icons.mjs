// Generates the data behind Storybook's "Fondations/Icônes" page, so it can never drift from the code:
// - kit-icons.generated.ts: every Lucide icon actually imported by a kit component (src + labs, stories and
//   specs excluded), with the components using it — read from the real `import … from '@lucide/angular'`.
// - lucide-library.generated.ts: every icon of the INSTALLED @lucide/angular (name, class, selector, aliases,
//   SVG nodes). Plain data, no Angular class: the page `import()`s it only when its tab is opened, so this
//   ~1 MB chunk stays out of the rest of Storybook.
// Both files are git-ignored. Run automatically by `npm run storybook`, `build-storybook` and `test`.
import '@angular/compiler'; // the package's partially-compiled components need the JIT facade to load in Node
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const lucide = await import('@lucide/angular');

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const lib = join(root, 'angular-components');
const out = join(lib, 'src/stories/icons/generated');

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(entries.map((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)])));
  return files.flat();
}

const pascal = (s) => s.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const isIcon = (k) => k.startsWith('Lucide') && typeof lucide[k] === 'function' && !!lucide[k].icon;
/** First attribute selector of the class (`svg[lucideHouse]` → `lucideHouse`), aliases excluded. */
const selectorOf = (cls) => cls.ɵcmp.selectors[0][1];

// ---- Icons used by the kit --------------------------------------------------------------------------
const sources = [...(await walk(join(lib, 'src'))), ...(await walk(join(lib, 'labs/src')))].filter(
  (f) => f.endsWith('.ts') && !/\.(spec|stories)\.ts$/.test(f) && !f.includes('/testing/') && !f.includes('/stories/'),
);

const used = new Map(); // canonical class name -> { importedAs: Set, components: Map<label, labs> }
for (const file of sources) {
  const code = await readFile(file, 'utf8');
  const names = [...code.matchAll(/import\s*\{([^}]*)\}\s*from\s*['"]@lucide\/angular['"]/g)]
    .flatMap((m) => m[1].split(','))
    .map((s) => s.trim().split(/\s+as\s+/)[0].replace(/^type\s+/, ''))
    .filter(isIcon);
  if (!names.length) continue;
  const labs = relative(lib, file).startsWith('labs/');
  // The component a file belongs to: its own exported class, else the folder's component (data files such
  // as side-navigation/navigation-presets.ts feed the component of the same folder).
  const cls = code.match(/export class (Soc\w+)/)?.[1];
  const component = cls ?? `Soc${labs ? 'Labs' : ''}${pascal(basename(dirname(file)))}`;
  for (const name of names) {
    const canonical = lucide[name].name;
    const entry = used.get(canonical) ?? { importedAs: new Set(), components: new Map() };
    if (name !== canonical) entry.importedAs.add(name);
    entry.components.set(component, labs);
    used.set(canonical, entry);
  }
}

const kit = [...used.entries()].sort(([a], [b]) => a.localeCompare(b));
const kitTs = `// GENERATED by scripts/generate-icons.mjs — do not edit, do not commit.
import { ${kit.map(([c]) => c).join(', ')} } from '@lucide/angular';
import type { KitIcon } from '../icon-types';

export const KIT_ICONS: KitIcon[] = [
${kit
  .map(([c, e]) => {
    const components = [...e.components.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, labs]) => ({ name, labs }));
    return `  ${JSON.stringify({
      name: lucide[c].icon.name,
      className: c,
      selector: selectorOf(lucide[c]),
      aliases: lucide[c].icon.aliases ?? [],
      importedAs: [...e.importedAs].sort(),
      components,
    }).replace(/}$/, `, icon: ${c} }`)},`;
  })
  .join('\n')}
];
`;

// ---- Full library ------------------------------------------------------------------------------------
const library = Object.keys(lucide)
  .filter((k) => isIcon(k) && lucide[k].name === k) // canonical classes only, deprecated aliases folded in
  .sort()
  .map((k) => ({
    name: lucide[k].icon.name,
    className: k,
    selector: selectorOf(lucide[k]),
    aliases: lucide[k].icon.aliases ?? [],
    node: lucide[k].icon.node.map(([tag, { key, ...attrs }, ...children]) => [tag, attrs, ...children]), // `key` is React bookkeeping
  }));
const { version } = JSON.parse(await readFile(join(root, 'node_modules/@lucide/angular/package.json'), 'utf8'));
const libraryTs = `// GENERATED by scripts/generate-icons.mjs — do not edit, do not commit.
import type { LibraryIcon } from '../icon-types';

export const LUCIDE_VERSION = ${JSON.stringify(version)};
export const LUCIDE_LIBRARY: LibraryIcon[] = ${JSON.stringify(library)};
`;

await mkdir(out, { recursive: true });
await writeFile(join(out, 'kit-icons.generated.ts'), kitTs);
await writeFile(join(out, 'lucide-library.generated.ts'), libraryTs);
console.log(`generate-icons: ${kit.length} icônes utilisées par le kit, ${library.length} dans @lucide/angular ${version}`);
